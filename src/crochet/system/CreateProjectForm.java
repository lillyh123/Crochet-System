    private void SaveButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SaveButtonActionPerformed
        String title = TitleTxt.getText();
        String description = DescriptionTxt.getText();
        String type = String.valueOf(TypeCombo.getSelectedItem());
        String row = RowNumTxt.getText();
        String pattern = PatternTxt.getText().replaceAll("\\n", "!newline!");
      
        //https://www.w3schools.com/java/java_date.asp 
        LocalDate date = LocalDate.now(); 
        DateTimeFormatter dateFormat = DateTimeFormatter.ofPattern("dd/MM/yyyy");
        String dateFormatted = date.format(dateFormat);
        
         String dateStarted = dateFormatted;
        
        if(pattern.equals(" ") || pattern.equals("")){
            pattern = "N/A";
        }
        
        if(u1.presenceCheck(title) && u1.presenceCheck(description) && u1.presenceCheck(row)){
            if(u1.typeCheck(row, "Int")){
                try {
                    int id = u1.getID("ProjectID.txt");
                    String record = id+","+title+","+description+","+type+","+row+","+pattern+","+dateStarted;
                    u1.writeToFile("UserProjects.txt", record);
                    UserProjectsRecord u = new UserProjectsRecord(id,title,description,type,Integer.valueOf(row),pattern,dateStarted);
                    Data.projectsMap.put(String.valueOf(id), u);
                    
                    JOptionPane.showMessageDialog(rootPane, "Success! Project titlted "+title+" has been saved!"); 
                    TitleTxt.setText("");
                    DescriptionTxt.setText("");
                    RowNumTxt.setText("");
                    PatternTxt.setText("");
                    
                } catch (IOException ex) {
                    Logger.getLogger(CreateProjectForm.class.getName()).log(Level.SEVERE, null, ex);
                }
            }
            else{
               JOptionPane.showMessageDialog(rootPane, "Error! Row number must be a whole number!"); 
            }
        }
        else{
            JOptionPane.showMessageDialog(rootPane, "Error! All fields, other than Pattern, must contain text!");
        }
    }//GEN-LAST:event_SaveButtonActionPerformed

