    private void SubmitButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SubmitButtonActionPerformed
        String reason = String.valueOf(ReasonCombo.getSelectedItem());
        String comments = CommentsTextbox.getText();
        //no validation, as  comments are optional and the combobox means something is definitely selected
        int choice = JOptionPane.showConfirmDialog(rootPane, "Are you sure you want submit this report?");
        if(choice == JOptionPane.YES_OPTION){
            int reportid = 0;
            try {
                reportid = u1.getID("ReportID.txt");
            } catch (IOException ex) {
                Logger.getLogger(ReportingForm.class.getName()).log(Level.SEVERE, null, ex);
            }
            if(comments.equals(" ") || comments.equals("")){
                comments = "N/A";
            }
            comments = comments.replaceAll("\\n", "!newline!");
            String record = reportid+","+adviceid+","+main.username+","+reason+","+comments;
            try {
                u1.writeToFile("Reports.txt", record);
                CommentsTextbox.setText(" ");
                JOptionPane.showMessageDialog(rootPane, "Successfully reported advice!");
            } catch (IOException ex) {
                Logger.getLogger(ReportingForm.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }//GEN-LAST:event_SubmitButtonActionPerformed

