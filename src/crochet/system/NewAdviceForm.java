    private void SaveButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SaveButtonActionPerformed
       String title = Titletxt.getText();
       String content = Contenttxt.getText().replaceAll("\\n", "!newline!");
       String type = String.valueOf(AdviceTypeCombo.getSelectedItem());
       String adviserusername = main.username;
        
       boolean validation = false;
       
       if(u1.presenceCheck(title) && u1.presenceCheck(content)){
           if(u1.lengthCheck(content, false, 20)){
               validation = true;
           }
           else{
               JOptionPane.showMessageDialog(rootPane, "Error! Content must be at least 20 characters!");
           }
       }
       else{
           JOptionPane.showMessageDialog(rootPane, "Error! All fields must contain text!");
       }
       
       if(validation){
           int id = 0;
           try {
               //record + write to file
               id  = u1.getID("AdviceID.txt");
               String record = String.valueOf(id)+","+title+","+content+","+type+","+adviserusername+","+String.valueOf(0);
               u1.writeToFile("Advice.txt", record);
               AdviceRecord a = new AdviceRecord(id,title,content,type,adviserusername,0);
               Data.adviceMap.put(String.valueOf(id), a);
               
               Titletxt.setText(" ");
               Contenttxt.setText(" ");
               
               JOptionPane.showMessageDialog(rootPane, "Success! Advice titled "+title+" saved!");
               main.loadProducts();
               main.loadAdviceItems();
               main.setVisible(true);
               this.dispose();
               
               

           } catch (IOException ex) {
               Logger.getLogger(NewAdviceForm.class.getName()).log(Level.SEVERE, null, ex);
           }
       }
    }//GEN-LAST:event_SaveButtonActionPerformed

